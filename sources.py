def all_boards():
    """모든 게시판을 (탭, 게시판) 짝으로 돌려줍니다."""
    for tab in TABS:
        for board in tab["boards"]:
            yield tab, board


def find_board(board_key):
    """게시판 키로 (탭, 게시판) 을 찾습니다. 없으면 (None, None)."""
    for tab, board in all_boards():
        if board["board_key"] == board_key:
            return tab, board
    return None, None


def find_tab(tab_key):
    for tab in TABS:
        if tab["key"] == tab_key:
            return tab
    return None


def expand_synonyms(text):
    """글에 들어 있는 낱말과 같은 뜻인 낱말들을 함께 돌려줍니다.

    찾을 때가 아니라 **저장할 때** 넓히는 쪽을 골랐습니다. 글 하나에
    '법학적성시험'이 있으면 '리트'도 같이 적어 둡니다. 그러면 찾는 쪽은
    글자만 맞춰 보면 되고, 챗봇(자바스크립트)에 같은 표를 또 둘 필요가
    없습니다.
    """
    lowered = (text or "").lower()
    extra = []
    for group in SYNONYM_GROUPS:
        if any(word.lower() in lowered for word in group):
            extra.extend(group)
    return extra
